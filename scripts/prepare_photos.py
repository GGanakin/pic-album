def collection_for(number):
    if number <= 5899:
        return "forest"
    if 5940 <= number <= 6014:
        return "white"
    if number >= 6103:
        return "garden"
    return "classic"


def prepare(path):
    photo_id = path.name.split("_")[0]
    number = int(re.search(r"(\d{4})$", photo_id).group(1))
    preview = OUTPUT / f"{photo_id}.webp"
    thumb = OUTPUT / f"{photo_id}-thumb.webp"
    with Image.open(path) as original:
        im = ImageOps.exif_transpose(original)
        width, height = im.size
        if not preview.exists() or not thumb.exists() or preview.stat().st_mtime < path.stat().st_mtime:
            profile = im.info.get("icc_profile")
            if profile:
                try:
                    im = ImageCms.profileToProfile(
                        im, ImageCms.ImageCmsProfile(BytesIO(profile)),
                        ImageCms.createProfile("sRGB"), outputMode="RGB"
                    )
                except (OSError, ValueError, ImageCms.PyCMSError):
                    im = im.convert("RGB")
            else:
                im = im.convert("RGB")
            im.thumbnail((2400, 2400), Image.Resampling.LANCZOS)
            im.save(preview, "WEBP", quality=86, method=4)
            im.thumbnail((760, 760), Image.Resampling.LANCZOS)
            im.save(thumb, "WEBP", quality=82, method=4)
    return {
        "id": photo_id, "collection": collection_for(number),
        "width": width, "height": height,
        "src": f"assets/photos/{photo_id}.webp",
        "thumb": f"assets/photos/{photo_id}-thumb.webp",
        "original": f"all_pic/{path.name}",
    }


def main():
    sources = sorted((ROOT / "all_pic").glob("*.jpg"))
    with ThreadPoolExecutor(max_workers=4) as pool:
        photos = list(pool.map(prepare, sources))
    counts = {item["id"]: 0 for item in COLLECTIONS}
    for photo in photos:
        key = photo["collection"]
        titles = TITLES[key]
        photo["title"] = titles[counts[key] % len(titles)]
        counts[key] += 1
    data = {"collections": COLLECTIONS, "photos": photos}
    (ROOT / "photos.js").write_text(
        "/* Generated by scripts/prepare_photos.py. Originals stay in all_pic/. */\n"
        "window.WEDDING_ALBUM = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    total = sum(path.stat().st_size for path in OUTPUT.glob("*.webp"))
    print(f"Prepared {len(photos)} photos ({total / 1024 / 1024:.1f} MB of previews).")
    print(json.dumps(counts, ensure_ascii=False))


if __name__ == "__main__":
    main()
